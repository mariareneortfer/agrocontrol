-- =====================================================================
-- AgroControl - Migracion V1: nucleo inicial del esquema
-- Programacion Aplicada 2026-2 - Clase 06
--
-- Crea las 6 tablas nucleo, en orden de dependencias:
--   1. predio            (raiz)
--   2. parcela           (depende de predio)
--   3. cultivo           (raiz)
--   4. campana           (depende de cultivo)
--   5. campana_parcela   (depende de campana y parcela)
--   6. labor             (depende de campana_parcela)
--
-- Fuente del diseno: docs/04-model/modelo-fisico-v0.1.md
-- Este script debe ejecutarse sobre una base de datos vacia.
--
-- Todas las tablas se crean dentro del esquema del proyecto, agrocontrol,
-- y no en el esquema public.
-- =====================================================================


-- 0. Esquema del proyecto.
CREATE SCHEMA IF NOT EXISTS agrocontrol;
SET search_path TO agrocontrol, public;


-- 1. predio: una fila representa una propiedad agricola.
CREATE TABLE predio (
    predio_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(100) NOT NULL,
    ubicacion   VARCHAR(200),
    descripcion TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_predio PRIMARY KEY (predio_id),
    -- RF-01: el cliente distingue sus predios por el nombre.
    CONSTRAINT uq_predio_nombre UNIQUE (nombre)
);


-- 2. parcela: una fila representa un lote agricola dentro de un predio.
CREATE TABLE parcela (
    parcela_id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    predio_id             BIGINT NOT NULL,
    codigo                VARCHAR(20) NOT NULL,
    nombre                VARCHAR(100) NOT NULL,
    superficie            NUMERIC(10,2) NOT NULL,
    unidad_superficie     VARCHAR(20) NOT NULL,
    ubicacion_referencial VARCHAR(200),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_parcela PRIMARY KEY (parcela_id),
    -- RF-01: una parcela no existe sin predio.
    CONSTRAINT fk_parcela_predio
        FOREIGN KEY (predio_id) REFERENCES predio (predio_id),
    -- RF-01: el codigo no se repite dentro del mismo predio (unicidad contextual).
    CONSTRAINT uq_parcela_predio_codigo UNIQUE (predio_id, codigo),
    -- RN-07: las cantidades deben ser validas.
    CONSTRAINT ck_parcela_superficie_positiva CHECK (superficie > 0)
);


-- 3. cultivo: una fila representa un cultivo del catalogo.
CREATE TABLE cultivo (
    cultivo_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(80) NOT NULL,
    variedad    VARCHAR(80),
    descripcion TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_cultivo PRIMARY KEY (cultivo_id),
    -- RF-02: no se repite un cultivo con la misma variedad.
    -- NULLS NOT DISTINCT: dos cultivos sin variedad tambien cuentan como repetidos.
    CONSTRAINT uq_cultivo_nombre_variedad UNIQUE NULLS NOT DISTINCT (nombre, variedad)
);


-- 4. campana: una fila representa un ciclo productivo de un cultivo
--    sobre una o varias parcelas.
CREATE TABLE campana (
    campana_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cultivo_id         BIGINT NOT NULL,
    nombre             VARCHAR(100) NOT NULL,
    fecha_inicio       DATE NOT NULL,
    fecha_fin_prevista DATE NOT NULL,
    fecha_cierre       DATE,
    estado             VARCHAR(20) NOT NULL DEFAULT 'activa',
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_campana PRIMARY KEY (campana_id),
    -- RF-03: una campana necesita saber que se cultiva.
    CONSTRAINT fk_campana_cultivo
        FOREIGN KEY (cultivo_id) REFERENCES cultivo (cultivo_id),
    -- RN-06, RN-09: conjunto cerrado de estados.
    CONSTRAINT ck_campana_estado CHECK (estado IN ('activa', 'finalizada')),
    -- RN-01: el periodo debe ser coherente.
    CONSTRAINT ck_campana_fechas CHECK (fecha_inicio <= fecha_fin_prevista),
    -- RN-09: una campana finalizada debe tener fecha de cierre.
    CONSTRAINT ck_campana_cierre
        CHECK (estado <> 'finalizada' OR fecha_cierre IS NOT NULL)
);


-- 5. campana_parcela: tabla puente. Una fila representa que una parcela
--    participa en una campana (relacion N:M).
CREATE TABLE campana_parcela (
    campana_parcela_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    campana_id         BIGINT NOT NULL,
    parcela_id         BIGINT NOT NULL,
    CONSTRAINT pk_campana_parcela PRIMARY KEY (campana_parcela_id),
    CONSTRAINT fk_campana_parcela_campana
        FOREIGN KEY (campana_id) REFERENCES campana (campana_id),
    CONSTRAINT fk_campana_parcela_parcela
        FOREIGN KEY (parcela_id) REFERENCES parcela (parcela_id),
    -- RN-01: una parcela no figura dos veces en la misma campana.
    CONSTRAINT uq_campana_parcela_campana_parcela UNIQUE (campana_id, parcela_id)
);


-- 6. labor: una fila representa un trabajo de campo planificado
--    en una parcela de una campana.
CREATE TABLE labor (
    labor_id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    campana_parcela_id BIGINT NOT NULL,
    tipo_labor         VARCHAR(40) NOT NULL,
    descripcion        TEXT,
    fecha_programada   DATE NOT NULL,
    fecha_inicio_real  TIMESTAMPTZ,
    fecha_fin_real     TIMESTAMPTZ,
    estado             VARCHAR(20) NOT NULL DEFAULT 'planificada',
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_labor PRIMARY KEY (labor_id),
    -- RN-02: toda labor pertenece a una campana y parcela.
    CONSTRAINT fk_labor_campana_parcela
        FOREIGN KEY (campana_parcela_id)
        REFERENCES campana_parcela (campana_parcela_id),
    -- RN-03: conjunto cerrado de estados.
    CONSTRAINT ck_labor_estado CHECK (
        estado IN ('planificada', 'asignada', 'en_ejecucion', 'completada', 'cancelada')
    ),
    -- RF-07: no se puede terminar antes de empezar.
    CONSTRAINT ck_labor_fechas_reales CHECK (fecha_inicio_real <= fecha_fin_real)
);
