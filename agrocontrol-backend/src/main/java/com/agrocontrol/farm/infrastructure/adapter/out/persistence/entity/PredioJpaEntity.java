package com.agrocontrol.farm.infrastructure.adapter.out.persistence.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * Entidad de PERSISTENCIA: mapea la tabla real agrocontrol.predio
 * creada por V1__init_core.sql. Cada atributo corresponde a una columna.
 * El schema (agrocontrol) lo fija application.yml con hibernate.default_schema.
 *
 * No se mapean created_at ni updated_at: PostgreSQL les pone valor con DEFAULT CURRENT_TIMESTAMP.
 */
@Entity
@Table(name = "predio")
public class PredioJpaEntity {

    // predio_id BIGINT GENERATED BY DEFAULT AS IDENTITY: lo genera PostgreSQL.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "predio_id")
    private Long id;

    // nombre VARCHAR(100) NOT NULL, UNIQUE (uq_predio_nombre).
    @Column(name = "nombre", nullable = false, length = 100, unique = true)
    private String nombre;

    // ubicacion VARCHAR(200), opcional.
    @Column(name = "ubicacion", length = 200)
    private String ubicacion;

    // descripcion TEXT, opcional.
    @Column(name = "descripcion", columnDefinition = "text")
    private String descripcion;

    /** Constructor vacio exigido por JPA (Hibernate lo usa al leer filas). */
    protected PredioJpaEntity() {
    }

    /** Para crear un predio nuevo: sin id, porque lo genera la base. */
    public PredioJpaEntity(String nombre, String ubicacion, String descripcion) {
        this.nombre = nombre;
        this.ubicacion = ubicacion;
        this.descripcion = descripcion;
    }

    public Long getId() {
        return id;
    }

    public String getNombre() {
        return nombre;
    }

    public String getUbicacion() {
        return ubicacion;
    }

    public String getDescripcion() {
        return descripcion;
    }
}
